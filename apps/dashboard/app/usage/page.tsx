import { Activity, Bot, Coins, MessageSquare, TrendingUp } from "lucide-react";
import { requireAdmin } from "@/lib/auth/admin";
import WorkspaceNav from "@/components/workspace-nav";

export const dynamic = "force-dynamic";

type SearchParams = { days?: string };
type UsageRow = {
  id: string; agent_id: string; provider: string; model: string;
  input_tokens: number | null; output_tokens: number | null; created_at: string;
  agents: { name: string; client_id: string; clients: { company: string } | null } | null;
};

const number = (value: number) => new Intl.NumberFormat("en-IN").format(value);

export default async function UsagePage({ searchParams }: { searchParams: Promise<SearchParams> }) {
  const params = await searchParams;
  const days = [7, 30, 90].includes(Number(params.days)) ? Number(params.days) : 30;
  const since = new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();
  const { supabase } = await requireAdmin();
  const { data, error } = await supabase.from("agent_usage")
    .select("id,agent_id,provider,model,input_tokens,output_tokens,created_at,agents(name,client_id,clients(company))")
    .gte("created_at", since).order("created_at", { ascending: false }).limit(2000);
  if (error) throw new Error(error.message);

  const rows = (data ?? []) as unknown as UsageRow[];
  const totalInput = rows.reduce((sum, row) => sum + (row.input_tokens ?? 0), 0);
  const totalOutput = rows.reduce((sum, row) => sum + (row.output_tokens ?? 0), 0);
  const agentMap = new Map<string, { name: string; client: string; requests: number; tokens: number }>();
  const clientMap = new Map<string, { name: string; requests: number; tokens: number }>();
  for (const row of rows) {
    const agent = row.agents;
    const agentName = agent?.name ?? "Unknown agent";
    const clientName = agent?.clients?.company ?? "Unassigned client";
    const agentStats = agentMap.get(row.agent_id) ?? { name: agentName, client: clientName, requests: 0, tokens: 0 };
    agentStats.requests += 1;
    agentStats.tokens += (row.input_tokens ?? 0) + (row.output_tokens ?? 0);
    agentMap.set(row.agent_id, agentStats);
    const clientStats = clientMap.get(agent?.client_id ?? "unknown") ?? { name: clientName, requests: 0, tokens: 0 };
    clientStats.requests += 1;
    clientStats.tokens += (row.input_tokens ?? 0) + (row.output_tokens ?? 0);
    clientMap.set(agent?.client_id ?? "unknown", clientStats);
  }
  const agents = [...agentMap.values()].sort((a,b) => b.tokens - a.tokens);
  const clients = [...clientMap.values()].sort((a,b) => b.tokens - a.tokens);
  const maxAgentTokens = Math.max(1, ...agents.map(item => item.tokens));
  const maxClientTokens = Math.max(1, ...clients.map(item => item.tokens));

  return <main className="usage-page">
    <WorkspaceNav />
    <header className="usage-header">
      <div><div className="eyebrow"><Activity size={13}/> PLATFORM INSIGHTS</div><h1>Usage &amp; analytics</h1><p>Track model requests and token consumption across your client workspaces.</p></div>
      <form action="/usage" className="usage-range"><label htmlFor="days">Period</label><select id="days" name="days" defaultValue={String(days)}><option value="7">Last 7 days</option><option value="30">Last 30 days</option><option value="90">Last 90 days</option></select><button type="submit">Apply</button></form>
    </header>
    <section className="usage-metrics">
      <article><span className="usage-metric-icon"><Activity size={17}/></span><small>Model requests</small><strong>{number(rows.length)}</strong><em>Recorded API calls</em></article>
      <article><span className="usage-metric-icon"><Coins size={17}/></span><small>Total tokens</small><strong>{number(totalInput + totalOutput)}</strong><em>Input + output tokens</em></article>
      <article><span className="usage-metric-icon"><MessageSquare size={17}/></span><small>Input tokens</small><strong>{number(totalInput)}</strong><em>Sent to AI providers</em></article>
      <article><span className="usage-metric-icon"><TrendingUp size={17}/></span><small>Output tokens</small><strong>{number(totalOutput)}</strong><em>Generated by AI providers</em></article>
    </section>
    <div className="usage-grid">
      <section className="usage-panel"><div className="usage-panel-head"><div><h2>Usage by agent</h2><p>Token consumption per agent</p></div><Bot size={17}/></div>
        {agents.length ? <div className="usage-bars">{agents.map(item=><div className="usage-bar-row" key={item.name + item.client}><div className="usage-bar-label"><b>{item.name}</b><span>{number(item.tokens)} tokens · {item.requests} requests</span></div><div className="usage-track"><i style={{width: (item.tokens / maxAgentTokens * 100) + "%"}}/></div><small>{item.client}</small></div>)}</div> : <div className="usage-empty"><Activity size={25}/><b>No usage recorded yet</b><span>Usage will appear here after an agent successfully completes an AI request.</span></div>}
      </section>
      <section className="usage-panel"><div className="usage-panel-head"><div><h2>Usage by client</h2><p>Compare client workspace activity</p></div></div>
        {clients.length ? <div className="usage-bars">{clients.map(item=><div className="usage-bar-row" key={item.name}><div className="usage-bar-label"><b>{item.name}</b><span>{number(item.tokens)} tokens · {item.requests} requests</span></div><div className="usage-track"><i style={{width: (item.tokens / maxClientTokens * 100) + "%"}}/></div></div>)}</div> : <div className="usage-empty"><MessageSquare size={25}/><b>No client activity yet</b><span>Client usage summaries will appear after successful agent requests.</span></div>}
      </section>
    </div>
    <section className="usage-panel usage-table-panel"><div className="usage-panel-head"><div><h2>Recent model activity</h2><p>Latest recorded requests within the selected period</p></div><span className="usage-limit">Up to 2,000 records</span></div>
      {rows.length ? <div className="usage-table-wrap"><table className="usage-table"><thead><tr><th>Agent / client</th><th>Provider</th><th>Model</th><th>Input</th><th>Output</th><th>Date</th></tr></thead><tbody>{rows.slice(0,100).map(row=><tr key={row.id}><td><b>{row.agents?.name ?? "Unknown agent"}</b><small>{row.agents?.clients?.company ?? "Unassigned client"}</small></td><td>{row.provider}</td><td>{row.model}</td><td>{number(row.input_tokens ?? 0)}</td><td>{number(row.output_tokens ?? 0)}</td><td>{new Date(row.created_at).toLocaleString()}</td></tr>)}</tbody></table></div> : <div className="usage-empty compact"><span>No model activity for this period.</span></div>}
    </section>
    <p className="usage-note">Token totals are based on usage records returned by the platform. Monetary cost estimates are intentionally omitted until provider pricing and billing rules are configured.</p>
  </main>;
}
